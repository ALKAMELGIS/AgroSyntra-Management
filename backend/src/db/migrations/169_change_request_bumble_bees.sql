-- Migration 169: bumble-bee change requests.
--
-- A scouter's bumble-bee changes (new deployment, boxes on hand, incoming
-- orders, inspection edits/deletes) now wait in ipm_change_requests until the
-- pest agronomist approves them. Nothing is written to the live bumble-bee
-- tables until then.
--
-- 1. A proposal to CREATE something (a deployment, an order) or to SET the
--    site's boxes on hand has no existing record, so entity_id may be empty.
-- 2. The action list grows: create, set (boxes on hand) and receive (an order).

ALTER TABLE ipm_change_requests ALTER COLUMN entity_id DROP NOT NULL;

-- The action CHECK from migration 106 was created inline, so its name is
-- generated by Postgres. Find it by its definition and drop it.
DO $$
DECLARE
  c RECORD;
BEGIN
  FOR c IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'ipm_change_requests'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%action%'
  LOOP
    EXECUTE format('ALTER TABLE ipm_change_requests DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

ALTER TABLE ipm_change_requests
  ADD CONSTRAINT ipm_change_requests_action_check
  CHECK (action IN ('update', 'delete', 'create', 'set', 'receive'));

-- The Bumble Bees page lists the caller's own open and rejected proposals.
CREATE INDEX IF NOT EXISTS idx_ipm_change_requests_org_requester
  ON ipm_change_requests (organization_id, requested_by, status);
